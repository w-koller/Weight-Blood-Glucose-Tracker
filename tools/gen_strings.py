"""Generates app/src/main/res/values/strings.xml from the copy in strings_*.py.

The copy lives in Python so it can be read and edited as plain sentences; this script handles
Android's escaping rules. Run it after changing any copy: python3 tools/gen_strings.py
"""
import glob
import importlib.util
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def escape(text: str) -> str:
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    return text


strings, plurals = {}, {}
for path in sorted(glob.glob(os.path.join(ROOT, "tools", "strings_*.py"))):
    spec = importlib.util.spec_from_file_location(os.path.basename(path)[:-3], path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    for key in module.STRINGS:
        assert key not in strings, f"duplicate string {key}"
    strings.update(module.STRINGS)
    plurals.update(getattr(module, "PLURALS", {}))

lines = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/gen_strings.py. Please edit the copy there. -->", "<resources>"]
for key, value in strings.items():
    attrs = ' formatted="false"' if "%" in value and "$" not in value else ""
    lines.append(f'    <string name="{key}"{attrs}>{escape(value)}</string>')
for key, forms in plurals.items():
    lines.append(f'    <plurals name="{key}">')
    for quantity, value in forms.items():
        lines.append(f'        <item quantity="{quantity}">{escape(value)}</item>')
    lines.append("    </plurals>")
lines.append("</resources>")

out = os.path.join(ROOT, "app", "src", "main", "res", "values", "strings.xml")
with open(out, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
print(f"{len(strings)} strings and {len(plurals)} plurals written to {os.path.relpath(out, ROOT)}")
